import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

function runGit(args) {
  return execFileSync('git', args, {
    cwd: rootDir,
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'ignore'],
  }).trim();
}

export function collectBuildInfo() {
  let commit = 'unknown';
  let commitDate = 'unknown';
  let branch = process.env.GITHUB_HEAD_REF || process.env.GITHUB_REF_NAME || 'unknown';

  try {
    commit = runGit(['rev-parse', 'HEAD']);
  } catch {
    // Source archive without git metadata.
  }

  if (commit !== 'unknown') {
    try {
      commitDate = runGit(['log', '-1', '--format=%cI']);
    } catch {
      // Unparsable history.
    }
  }

  if (branch === 'unknown') {
    try {
      branch = runGit(['symbolic-ref', '--quiet', '--short', 'HEAD']);
    } catch {
      // Detached checkout.
    }
  }

  const revision = commit === 'unknown' ? commit : commit.slice(0, 12);
  const { version } = JSON.parse(readFileSync(path.join(rootDir, 'package.json'), 'utf8'));

  return {
    version,
    branch,
    commit,
    commitDate,
    revision,
    builtAt: new Date().toISOString(),
  };
}

export function writeBuildInfoFile(info = collectBuildInfo()) {
  const outPath = path.join(rootDir, 'web', 'js', 'build_info.js');
  const content = [
    '// Generated by scripts/generate-build-info.mjs',
    `globalThis.__BUILD_INFO__ = ${JSON.stringify(info, null, 2)};`,
    '',
  ].join('\n');
  writeFileSync(outPath, content, 'utf8');
  return outPath;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const info = collectBuildInfo();
  const outPath = writeBuildInfoFile(info);
  console.log(`Wrote build info to ${path.relative(rootDir, outPath)} (${info.branch} @ ${info.revision})`);
}
